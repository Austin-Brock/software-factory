"""Lambda handlers: the webhook receiver and the background planning worker.

Linear waits only 5 seconds for a webhook response, but a plan takes 15-30s,
so the receiver verifies and acknowledges quickly and hands off to the worker.
"""

import base64
import json
import logging
import os
import time
import uuid
from functools import cache

import boto3
from botocore.config import Config
from botocore.exceptions import ClientError

from . import webhook
from .client import LinearClient

logger = logging.getLogger()
logger.setLevel(logging.INFO)

# Deliveries are remembered for a week; Linear's last retry comes after 6 hours.
DEDUPE_TTL_SECONDS = 7 * 24 * 3600
# The planner returns one response after generation finishes. Retrying would
# start a second billed run, so retries are off.
AGENTCORE_CONFIG = Config(read_timeout=300, retries={"total_max_attempts": 1})

PLAN_HEADER = "📋 **Implementation plan** · generated by software-factory planner"


@cache
def _parameter(name: str) -> str:
    response = boto3.client("ssm").get_parameter(Name=name, WithDecryption=True)
    return response["Parameter"]["Value"]


def _response(status: int, body: dict) -> dict:
    return {
        "statusCode": status,
        "headers": {"Content-Type": "application/json"},
        "body": json.dumps(body),
    }


def _raw_body(event: dict) -> bytes:
    body = event.get("body") or ""
    if event.get("isBase64Encoded"):
        return base64.b64decode(body)
    return body.encode()


def _remember_delivery(delivery_id: str) -> bool:
    """Record a delivery; False if it was already seen (a Linear retry)."""
    try:
        boto3.client("dynamodb").put_item(
            TableName=os.environ["DEDUPE_TABLE"],
            Item={
                "pk": {"S": f"delivery#{delivery_id}"},
                "expiresAt": {"N": str(int(time.time()) + DEDUPE_TTL_SECONDS)},
            },
            ConditionExpression="attribute_not_exists(pk)",
        )
    except ClientError as exc:
        if exc.response["Error"]["Code"] == "ConditionalCheckFailedException":
            return False
        raise
    return True


def receiver(event, context):
    headers = {k.lower(): v for k, v in (event.get("headers") or {}).items()}
    raw = _raw_body(event)

    try:
        secret = _parameter(os.environ["WEBHOOK_SECRET_PARAM"])
    except ClientError:
        logger.exception("Webhook signing secret is not configured")
        return _response(503, {"error": "not configured"})

    if not webhook.signature_is_valid(raw, headers.get("linear-signature"), secret):
        return _response(401, {"error": "invalid signature"})
    payload = json.loads(raw)
    if not webhook.is_fresh(payload):
        return _response(401, {"error": "stale delivery"})

    label_ids = webhook.added_label_ids(payload)
    if not label_ids:
        return _response(200, {"ignored": "no label added"})

    delivery_id = headers.get("linear-delivery") or str(uuid.uuid4())
    if not _remember_delivery(delivery_id):
        return _response(200, {"ignored": "duplicate delivery"})

    boto3.client("lambda").invoke(
        FunctionName=os.environ["WORKER_FUNCTION"],
        InvocationType="Event",
        Payload=json.dumps(
            {
                "issueId": payload["data"]["id"],
                "addedLabelIds": label_ids,
                "deliveryId": delivery_id,
            }
        ).encode(),
    )
    return _response(202, {"accepted": delivery_id})


def format_ticket(issue: dict) -> str:
    # Ticket text is user-written; mark it as data so the planner treats it that way.
    return (
        f"Linear issue {issue['identifier']}: {issue['title']}\n\n"
        f"<ticket>\n{issue.get('description') or '(no description)'}\n</ticket>"
    )


def run_planner(ticket: str) -> dict:
    client = boto3.client("bedrock-agentcore", config=AGENTCORE_CONFIG)
    try:
        response = client.invoke_agent_runtime(
            agentRuntimeArn=os.environ["PLANNER_RUNTIME_ARN"],
            runtimeSessionId=str(uuid.uuid4()),
            payload=json.dumps({"ticket": ticket}).encode(),
            contentType="application/json",
            accept="application/json",
        )
    except ClientError as exc:
        code = exc.response["Error"]["Code"]
        logger.exception("Planner invocation failed")
        if code == "AccessDeniedException":
            return {"error": "Planner is paused", "details": "The monthly budget kill switch may be engaged."}
        return {"error": "Planner invocation failed", "details": code}
    return json.loads(response["response"].read())


def error_comment(result: dict) -> str:
    return f"⚠️ **software-factory could not produce a plan:** {result.get('error', 'unknown error')}\n\n{result.get('details', '')}".strip()


def worker(event, context):
    linear = LinearClient(_parameter(os.environ["LINEAR_API_KEY_PARAM"]))
    issue = linear.get_issue(event["issueId"])

    names = {node["id"]: node["name"] for node in issue["labels"]["nodes"]}
    trigger = os.environ["TRIGGER_LABEL"]
    if not any(names.get(label_id) == trigger for label_id in event["addedLabelIds"]):
        logger.info("Skipping %s: %s was not added", issue["identifier"], trigger)
        return {"skipped": issue["identifier"]}

    result = run_planner(format_ticket(issue))
    if "plan" in result:
        linear.comment(issue["id"], f"{PLAN_HEADER}\n\n{result['plan']}")
        logger.info("Posted plan on %s", issue["identifier"])
        return {"planned": issue["identifier"]}

    logger.error("Planner returned an error for %s: %s", issue["identifier"], result)
    linear.comment(issue["id"], error_comment(result))
    return {"failed": issue["identifier"]}
