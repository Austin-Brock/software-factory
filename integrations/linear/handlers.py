"""Lambda handlers: the webhook receiver and the background planning worker.

Linear waits only 5 seconds for a webhook response, but a plan takes 15-30s,
so the receiver verifies and acknowledges quickly and hands off to the worker.
"""

import base64
import json
import logging
import os
import re
import time
import urllib.error
import uuid
from functools import cache

import boto3
from botocore.config import Config
from botocore.exceptions import BotoCoreError, ClientError

from ..github import rules
from ..github.client import GitHubApp, GitHubError, open_pull_request
from . import webhook
from .client import LinearClient, LinearError

logger = logging.getLogger()
logger.setLevel(logging.INFO)

# Deliveries are remembered for a week; Linear's last retry comes after 6 hours.
DEDUPE_TTL_SECONDS = 7 * 24 * 3600
# Secrets are re-read periodically so rotations take effect on warm Lambdas.
PARAMETER_TTL_SECONDS = 300
# Stay well under the planner's 20,000-character ticket limit.
MAX_DESCRIPTION_CHARS = 15_000
# The planner returns one response after it finishes exploring and writing.
# The timeout sits below the worker's 10-minute limit so a slow run still gets
# an error comment; retries are off because a retry would start a second
# billed run.
AGENTCORE_CONFIG = Config(read_timeout=540, retries={"total_max_attempts": 1})
# Builds can take up to 12 minutes; the build worker runs for up to 15.
BUILDER_CONFIG = Config(read_timeout=840, retries={"total_max_attempts": 1})

PLAN_HEADER = "📋 **Implementation plan** · generated by software-factory planner"

_parameters: dict[str, tuple[str, float]] = {}


@cache
def _client(service: str, config: Config | None = None):
    # Created once per container; the receiver has only 5 seconds per request.
    if config is None and service == "bedrock-agentcore":
        config = AGENTCORE_CONFIG
    return boto3.client(service, config=config)


def _parameter(name: str) -> str:
    cached = _parameters.get(name)
    if cached and time.monotonic() - cached[1] < PARAMETER_TTL_SECONDS:
        return cached[0]
    response = _client("ssm").get_parameter(Name=name, WithDecryption=True)
    value = response["Parameter"]["Value"]
    _parameters[name] = (value, time.monotonic())
    return value


def _response(status: int, body: dict) -> dict:
    return {
        "statusCode": status,
        "headers": {"Content-Type": "application/json"},
        "body": json.dumps(body),
    }


def _raw_body(event: dict) -> bytes:
    body = event.get("body") or ""
    if event.get("isBase64Encoded"):
        return base64.b64decode(body)
    return body.encode()


def _delivery_key(delivery_id: str) -> dict:
    return {"pk": {"S": f"delivery#{delivery_id}"}}


def _remember_delivery(delivery_id: str) -> bool:
    """Record a delivery; False if it was already seen (a Linear retry)."""
    try:
        _client("dynamodb").put_item(
            TableName=os.environ["DEDUPE_TABLE"],
            Item={
                **_delivery_key(delivery_id),
                "expiresAt": {"N": str(int(time.time()) + DEDUPE_TTL_SECONDS)},
            },
            ConditionExpression="attribute_not_exists(pk)",
        )
    except ClientError as exc:
        if exc.response["Error"]["Code"] == "ConditionalCheckFailedException":
            return False
        raise
    return True


def _forget_delivery(delivery_id: str) -> None:
    _client("dynamodb").delete_item(
        TableName=os.environ["DEDUPE_TABLE"], Key=_delivery_key(delivery_id)
    )


def receiver(event, context):
    headers = {k.lower(): v for k, v in (event.get("headers") or {}).items()}
    raw = _raw_body(event)

    try:
        secret = _parameter(os.environ["WEBHOOK_SECRET_PARAM"])
    except ClientError:
        logger.exception("Webhook signing secret is not configured")
        return _response(503, {"error": "not configured"})

    if not webhook.signature_is_valid(raw, headers.get("linear-signature"), secret):
        return _response(401, {"error": "invalid signature"})
    payload = json.loads(raw)
    if not webhook.is_fresh(payload):
        return _response(401, {"error": "stale delivery"})

    label_ids = webhook.added_label_ids(payload)
    if not label_ids:
        return _response(200, {"ignored": "no label added"})

    delivery_id = headers.get("linear-delivery") or str(uuid.uuid4())
    if not _remember_delivery(delivery_id):
        return _response(200, {"ignored": "duplicate delivery"})

    try:
        _client("lambda").invoke(
            FunctionName=os.environ["WORKER_FUNCTION"],
            InvocationType="Event",
            Payload=json.dumps(
                {
                    "issueId": payload["data"]["id"],
                    "addedLabelIds": label_ids,
                    "deliveryId": delivery_id,
                }
            ).encode(),
        )
    except (BotoCoreError, ClientError):
        # Forget the delivery so Linear's retry is processed instead of skipped.
        logger.exception("Could not hand delivery %s to the worker", delivery_id)
        _forget_delivery(delivery_id)
        return _response(500, {"error": "handoff failed"})
    # Linear treats any status other than 200 as a failed delivery and retries.
    return _response(200, {"accepted": delivery_id})


def format_ticket(issue: dict) -> str:
    description = issue.get("description") or "(no description)"
    if len(description) > MAX_DESCRIPTION_CHARS:
        description = description[:MAX_DESCRIPTION_CHARS] + "\n[description truncated]"
    # Ticket text is user-written; mark it as data so the planner treats it that way.
    return (
        f"Linear issue {issue['identifier']}: {issue['title']}\n\n"
        f"<ticket>\n{description}\n</ticket>"
    )


def repo_for_team(team_key: str | None) -> str | None:
    """The repository a Linear team's tickets are planned against, if any."""
    try:
        team_repos = json.loads(os.environ.get("TEAM_REPOS") or "{}")
    except ValueError:
        logger.error("TEAM_REPOS is not valid JSON; planning without a repo")
        return None
    if not isinstance(team_repos, dict):
        logger.error("TEAM_REPOS must be a JSON object; planning without a repo")
        return None
    repo = team_repos.get(team_key or "")
    return repo if isinstance(repo, str) else None


def run_planner(ticket: str, repo: str | None = None) -> dict:
    payload = {"ticket": ticket, **({"repo": repo} if repo else {})}
    return _invoke_runtime(os.environ["PLANNER_RUNTIME_ARN"], payload, AGENTCORE_CONFIG, "Planner")


def run_builder(ticket: str, plan: str, repo: str) -> dict:
    payload = {"ticket": ticket, "plan": plan, "repo": repo}
    return _invoke_runtime(os.environ["BUILDER_RUNTIME_ARN"], payload, BUILDER_CONFIG, "Builder")


def _invoke_runtime(arn: str, payload: dict, config: Config, name: str) -> dict:
    try:
        response = _client("bedrock-agentcore", config).invoke_agent_runtime(
            agentRuntimeArn=arn,
            runtimeSessionId=str(uuid.uuid4()),
            payload=json.dumps(payload).encode(),
            contentType="application/json",
            accept="application/json",
        )
        return json.loads(response["response"].read())
    except ClientError as exc:
        code = exc.response["Error"]["Code"]
        logger.exception("%s invocation failed", name)
        if code == "AccessDeniedException":
            return {"error": f"{name} is paused", "details": "The monthly budget kill switch may be engaged."}
        return {"error": f"{name} invocation failed", "details": code}
    except BotoCoreError as exc:
        logger.exception("%s did not respond", name)
        return {"error": f"{name} did not respond", "details": type(exc).__name__}
    except ValueError:
        logger.exception("%s returned a non-JSON response", name)
        return {"error": f"{name} returned an unreadable response"}


def error_comment(result: dict, action: str = "produce a plan") -> str:
    details = result.get("details", "")
    if isinstance(details, list):
        details = "; ".join(str(item.get("msg", item)) for item in details)
    return f"⚠️ **software-factory could not {action}:** {result.get('error', 'unknown error')}\n\n{details}".strip()


def worker(event, context):
    linear = LinearClient(_parameter(os.environ["LINEAR_API_KEY_PARAM"]))
    try:
        issue = linear.get_issue(event["issueId"])
    except (LinearError, urllib.error.URLError):
        logger.exception("Could not load issue %s from Linear", event["issueId"])
        return {"failed": event["issueId"]}
    if not issue:
        logger.warning("Issue %s no longer exists", event["issueId"])
        return {"skipped": event["issueId"]}

    names = {node["id"]: node["name"].casefold() for node in issue["labels"]["nodes"]}
    trigger = os.environ["TRIGGER_LABEL"].casefold()
    if not any(names.get(label_id) == trigger for label_id in event["addedLabelIds"]):
        logger.info("Skipping %s: %s was not added", issue["identifier"], trigger)
        return {"skipped": issue["identifier"]}

    repo = repo_for_team((issue.get("team") or {}).get("key"))
    result = run_planner(format_ticket(issue), repo)
    # Never post a header with no plan under it.
    planned = bool(str(result.get("plan") or "").strip())
    if "plan" in result and not planned:
        result = {"error": "Planner returned an empty plan", "details": "Relabel the ticket to try again."}
    body = f"{PLAN_HEADER}\n\n{result['plan']}" if planned else error_comment(result)
    if not planned:
        logger.error("Planner returned an error for %s: %s", issue["identifier"], result)

    try:
        linear.comment(issue["id"], body)
    except (LinearError, urllib.error.URLError):
        # Keep the (already paid for) plan recoverable from the logs.
        logger.exception("Could not comment on %s; comment body follows:\n%s", issue["identifier"], body)
        return {"failed": issue["identifier"]}

    logger.info("Posted %s on %s", "plan" if planned else "error", issue["identifier"])
    if planned and repo and os.environ.get("BUILD_FUNCTION"):
        # Builds start automatically once a plan is posted.
        _client("lambda").invoke(
            FunctionName=os.environ["BUILD_FUNCTION"],
            InvocationType="Event",
            Payload=json.dumps(
                {
                    "issueId": issue["id"],
                    "identifier": issue["identifier"],
                    "title": issue["title"],
                    "url": issue.get("url"),
                    "ticket": format_ticket(issue),
                    "plan": result["plan"],
                    "repo": repo,
                }
            ).encode(),
        )
    return {"planned" if planned else "failed": issue["identifier"]}


def branch_name(identifier: str, title: str) -> str:
    slug = re.sub(r"[^a-z0-9]+", "-", title.lower()).strip("-")[:40].strip("-")
    return f"factory/{identifier.lower()}-{slug}" if slug else f"factory/{identifier.lower()}"


def pr_body(event: dict, result: dict) -> str:
    checks = result.get("checks") or {}
    rows = "\n".join(
        f"| `{name}` | {'✅ passed' if c['passed'] else ('⏭️ skipped' if c['passed'] is None else '❌ failed')} |"
        for name, c in checks.items()
    )
    failures = "\n\n".join(
        f"<details><summary>❌ <code>{name}</code> output</summary>\n\n```\n{c['output'][-3000:]}\n```\n</details>"
        for name, c in checks.items()
        if c["passed"] is False
    )
    status = "All checks passed." if result.get("passed") else "**❌ Checks are failing — this PR is a draft.**"
    link = f"[{event['identifier']}]({event['url']})" if event.get("url") else event["identifier"]
    return (
        f"Implements {link}: {event['title']}\n\n"
        f"## Summary\n{result.get('summary', '').strip()}\n\n"
        f"## Checks (run by the builder)\n{status}\n\n| Check | Result |\n|---|---|\n{rows}\n\n"
        f"{failures}\n\n"
        f"<details><summary>Implementation plan</summary>\n\n{event['plan']}\n</details>\n\n"
        "---\n🏭 Built by software-factory. A human must review and merge this PR."
    )


def build_worker(event, context):
    """Run the builder for a planned ticket and open a PR with the result."""
    linear = LinearClient(_parameter(os.environ["LINEAR_API_KEY_PARAM"]))
    issue_id, identifier = event["issueId"], event["identifier"]

    result = run_builder(event["ticket"], event["plan"], event["repo"])
    if "changes" not in result:
        logger.error("Builder failed for %s: %s", identifier, result)
        linear.comment(issue_id, error_comment(result, "build this"))
        return {"failed": identifier}

    if problems := rules.change_problems(result["changes"]):
        logger.error("Rejected change for %s: %s", identifier, problems)
        linear.comment(
            issue_id,
            error_comment({"error": "The change was rejected", "details": "; ".join(problems)}, "open a PR"),
        )
        return {"rejected": identifier}

    try:
        app = GitHubApp(
            os.environ["GITHUB_APP_ID"],
            os.environ["GITHUB_INSTALLATION_ID"],
            _parameter(os.environ["GITHUB_APP_KEY_PARAM"]),
        )
        token = app.installation_token(event["repo"])
        pull = open_pull_request(
            token,
            event["repo"],
            base_sha=result["baseSha"],
            branch=branch_name(identifier, event["title"]),
            changes=result["changes"],
            commit_message=f"{identifier}: {event['title']}\n\nBuilt by software-factory.",
            title=f"{identifier}: {event['title']}",
            body=pr_body(event, result),
            draft=not result.get("passed"),
        )
    except (GitHubError, urllib.error.URLError, KeyError) as exc:
        logger.exception("Could not open a PR for %s", identifier)
        linear.comment(issue_id, error_comment({"error": "Could not open the pull request", "details": str(exc)}, "open a PR"))
        return {"failed": identifier}

    verdict = "all checks passed" if result.get("passed") else "❌ checks failing, opened as draft"
    linear.comment(issue_id, f"🔨 **Pull request opened:** [#{pull['number']}]({pull['url']}) ({verdict})")
    logger.info("Opened PR #%s for %s", pull["number"], identifier)
    return {"pr": pull["number"]}
